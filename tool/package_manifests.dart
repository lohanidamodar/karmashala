// Writes the package-manager manifests for one release — the Homebrew cask
// and formula, the Scoop manifests and the winget manifest set — from the
// release's SHA256SUMS.txt (tool/release_sums.dart). packaging/ in this
// repository is this script's output for the newest release; the release
// workflow runs it again into the tap and the bucket.
//
//   dart tool/package_manifests.dart --version 1.35.0 --sums SHA256SUMS.txt \
//     [--date 2026-11-22] [--out packaging] [--only homebrew,scoop,winget]
//
// Plain dart:io, so it needs no `pub get`. See packaging/README.md.
import 'dart:io';

const _repo = 'lohanidamodar/karmashala';
const _home = 'https://github.com/$_repo';
const _summary =
    'Agent development environment for Claude Code, Codex and Antigravity';
const _wingetId = 'PopupBits.Karmashala';
const _wingetSchema = '1.10.0';

/// Inno Setup's AppId (app/windows/installer/karmashala.iss) plus `_is1`:
/// the uninstall key winget matches an installed copy by.
const _innoProductCode = '{7B3E1D42-8C5A-4F19-A6D3-2E8F0B9C4A71}_is1';

void main(List<String> argv) {
  final args = _parse(argv);
  final version = args['version'];
  final sumsPath = args['sums'];
  if (version == null || sumsPath == null) {
    stderr.writeln(
      'usage: dart tool/package_manifests.dart --version <x.y.z> '
      '--sums <SHA256SUMS.txt> [--date <yyyy-mm-dd>] [--out <dir>] '
      '[--only homebrew,scoop,winget]',
    );
    exitCode = 64;
    return;
  }
  final sums = readSums(File(sumsPath).readAsStringSync());
  final date =
      args['date'] ?? DateTime.now().toUtc().toIso8601String().substring(0, 10);
  final out = args['out'] ?? 'packaging';
  final only = (args['only'] ?? 'homebrew,scoop,winget').split(',').toSet();
  final files = <String, String>{};
  try {
    if (only.contains('homebrew')) {
      files['homebrew/Casks/karmashala.rb'] = cask(version, sums);
      files['homebrew/Formula/karmashala-host.rb'] = formula(version, sums);
    }
    if (only.contains('scoop')) {
      files['scoop/karmashala.json'] = scoopApp(version, sums);
      files['scoop/karmashala-host.json'] = scoopHost(version, sums);
    }
    if (only.contains('winget')) {
      final dir = 'winget/manifests/p/PopupBits/Karmashala';
      // One version at a time: an older set left beside it is not a manifest
      // anybody should submit.
      final parent = Directory('$out/$dir');
      if (parent.existsSync()) {
        for (final old in parent.listSync().whereType<Directory>()) {
          if (old.path.split(RegExp(r'[\\/]')).last != version) {
            old.deleteSync(recursive: true);
          }
        }
      }
      files.addAll({
        for (final e in winget(version, sums, date).entries)
          '$dir/$version/${e.key}': e.value,
      });
    }
  } on MissingSum catch (error) {
    stderr.writeln(error);
    exitCode = 1;
    return;
  }
  for (final MapEntry(key: path, value: text) in files.entries) {
    final file = File('$out/$path');
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(text);
    stdout.writeln('wrote ${file.path}');
  }
}

class MissingSum implements Exception {
  MissingSum(this.name);
  final String name;
  @override
  String toString() => 'SHA256SUMS has no line for $name';
}

Map<String, String> readSums(String text) {
  final sums = <String, String>{};
  for (final line in text.split('\n')) {
    final match = RegExp(
      r'^([0-9a-fA-F]{64}) [ *](.+)$',
    ).firstMatch(line.trimRight());
    if (match != null) sums[match[2]!] = match[1]!.toLowerCase();
  }
  return sums;
}

String _sum(Map<String, String> sums, String name) =>
    sums[name] ?? (throw MissingSum(name));

String _download(String version, String name) =>
    '$_home/releases/download/v$version/$name';

String cask(String version, Map<String, String> sums) =>
    '''
# The Karmashala desktop app, from its GitHub release's DMG.
# Generated by tool/package_manifests.dart — edit that, not this.
cask "karmashala" do
  version "$version"
  sha256 "${_sum(sums, 'Karmashala-macOS-$version.dmg')}"

  url "$_home/releases/download/v#{version}/Karmashala-macOS-#{version}.dmg"
  name "Karmashala"
  desc "$_summary"
  homepage "$_home"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: ">= :monterey"

  app "karmashala.app"

  zap trash: [
    "~/.karmashala",
    "~/Library/Application Support/com.popupbits.karmashala",
    "~/Library/Caches/com.popupbits.karmashala",
    "~/Library/Preferences/com.popupbits.karmashala.plist",
    "~/Library/Saved Application State/com.popupbits.karmashala.savedState",
  ]

  caveats <<~EOS
    Karmashala is not notarised yet, so Gatekeeper blocks the first launch.
    Open it once with right-click > Open, or allow it in
    System Settings > Privacy & Security.
  EOS
end
''';

String formula(String version, Map<String, String> sums) {
  String bundle(String target) {
    final name = 'karmashala_host-$version-$target.tar.gz';
    return '      url "${_download(version, name)}"\n'
        '      sha256 "${_sum(sums, name)}"';
  }

  return '''
# The Karmashala server on its own: sessions, agents and the relay, headless.
# Generated by tool/package_manifests.dart — edit that, not this.
class KarmashalaHost < Formula
  desc "Headless Karmashala server: agent sessions and the relay"
  homepage "$_home"
  version "$version"
  license "Apache-2.0"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
${bundle('macos-arm64')}
    end
    on_intel do
${bundle('macos-x64')}
    end
  end

  on_linux do
    on_arm do
${bundle('linux-arm64')}
    end
    on_intel do
${bundle('linux-x64')}
    end
  end

  def install
    # A bundle, not a binary: the executable finds its SQLite at ../lib, so it
    # stays whole in libexec and bin gets a script that runs it there.
    libexec.install Dir["*"]
    (bin/"karmashala_host").write_env_script libexec/"bin/karmashala_host", {}
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/karmashala_host version")
    system bin/"karmashala_host", "probe-store"
  end
end
''';
}

