Map<String, String> winget(
  String version,
  Map<String, String> sums,
  String date,
) {
  final installer = 'Karmashala-Setup-$version.exe';
  String header(String kind) =>
      '# Generated by tool/package_manifests.dart in $_repo.\n'
      '# yaml-language-server: \$schema=https://aka.ms/winget-manifest.$kind.$_wingetSchema.schema.json\n\n'
      'PackageIdentifier: $_wingetId\n'
      'PackageVersion: $version\n';
  return {
    '$_wingetId.yaml':
        '${header('version')}'
        'DefaultLocale: en-US\n'
        'ManifestType: version\n'
        'ManifestVersion: $_wingetSchema\n',
    '$_wingetId.installer.yaml':
        '${header('installer')}'
        'InstallerType: inno\n'
        'Scope: machine\n'
        'ElevationRequirement: elevatesSelf\n'
        'UpgradeBehavior: install\n'
        "ProductCode: '$_innoProductCode'\n"
        'ReleaseDate: $date\n'
        'Installers:\n'
        '- Architecture: x64\n'
        '  InstallerUrl: ${_download(version, installer)}\n'
        '  InstallerSha256: ${_sum(sums, installer).toUpperCase()}\n'
        'ManifestType: installer\n'
        'ManifestVersion: $_wingetSchema\n',
    '$_wingetId.locale.en-US.yaml':
        '${header('defaultLocale')}'
        'PackageLocale: en-US\n'
        'Publisher: PopupBits\n'
        'PublisherUrl: https://popupbits.com\n'
        'PublisherSupportUrl: $_home/issues\n'
        'PackageName: Karmashala\n'
        'PackageUrl: $_home\n'
        'License: Apache-2.0\n'
        'LicenseUrl: $_home/blob/main/LICENSE\n'
        'ShortDescription: $_summary.\n'
        'Description: |-\n'
        '  Karmashala runs Claude Code, Codex and Antigravity in terminal panes and\n'
        '  chat views across your projects, with sessions that outlive the app, git\n'
        '  worktrees per task, and a companion app on your phone.\n'
        'Moniker: karmashala\n'
        'Tags:\n'
        '- ai\n'
        '- agents\n'
        '- claude-code\n'
        '- codex\n'
        '- developer-tools\n'
        '- terminal\n'
        'ReleaseNotesUrl: $_home/releases/tag/v$version\n'
        'ManifestType: defaultLocale\n'
        'ManifestVersion: $_wingetSchema\n',
  };
}

Map<String, String> _parse(List<String> argv) {
  final args = <String, String>{};
  for (var i = 0; i < argv.length; i++) {
    final arg = argv[i];
    if (!arg.startsWith('--')) continue;
    final eq = arg.indexOf('=');
    if (eq > 0) {
      args[arg.substring(2, eq)] = arg.substring(eq + 1);
    } else if (i + 1 < argv.length) {
      args[arg.substring(2)] = argv[++i];
    }
  }
  return args;
}
